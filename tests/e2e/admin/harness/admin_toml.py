"""The test server's admin.toml and its other trust files (docs/ADMIN.md §7, §1.3, §1.6).

Two workshops, as §7 sets them: `zab-admin-e2e`, whose bot is `Workshop admin · e2e` in
`#zab-dev-organizers` and which has no organizers of its own (`zab-tester` acts as a global
admin; `zab-tester2` is a stranger there, A1 and A15), and `zab-admin-e2e2`, organized by
`zab-tester2` alone. `admins = deployers = [zab-tester]`, `destructive_approvals = 1` (one test
user is a global admin), a plan TTL of 2 minutes (A3), `release = "rc"`, and the console
at `https://admin-e2e.localhost` (A11): Caddy gives a `.localhost` name a certificate of its
own CA, and the server resolves it to itself.
Each workshop has its alerts channel (`#zab-dev-alerts`, `#zab-dev-alerts-2`), which `!waker
on` needs (A8, A18); `zab-admin-e2e2` has its participants' channel too,
`#zab-dev-participants-2` (`channel`, #627), which A22's `!roster sync` reads; `zab-admin-e2e`
has a `gifts_step` (`GIFTS_STEP`, #709), which needs a release that knows the key (0.2.17): the
setup installs the file before it deploys the commit under test, and an older release's units
refuse it until then.
`[global]` holds the rig's scope (§5, #422): `zab-scope=admin-e2e`, its region, the fake
participants' instance type, and the extra scope tag `zab-role=test`, so the rendered role policy
has both tags in every condition. `zab-admin-e2e` has a `mention_after_s` (`MENTION_AFTER_S`,
#711), which needs a release that knows the key (0.2.17): the setup installs the file and then
deploys the commit under test, and an older release's units refuse the file until then.
The file holds IDs, not secrets, but it lives in the rig's directory, never in git.

**A9's variant** (`ending`), installed for A9 alone and the rig's put back after it: two
approvers for the destructive verbs, `destructive_approvals = 2`, with `zab-tester2` added to
`zab-admin-e2e`'s organizers, so that `zab-tester2` (an organizer: one of two) and then
`zab-tester` approve a `!teardown` or `!deactivate-bots` with the phrase (decided
#356), and `zab-tester`, a global admin, approves the spare's teardown alone (#558); and a plan
TTL of 15 minutes,
since step 4's teardown is approved after a `!protect off`, whose `protect.py` reads EC2 back
for up to 5 minutes (#378). Nothing else differs.
"""

from __future__ import annotations

import json

from e2e.admin.harness.rig import (
    ADMINS_CHANNEL,
    E2E,
    E2E2,
    GLOBAL_BOT,
    PARTICIPANT_TYPE,
    SCOPE,
    TEST_ROLE,
    Workshop,
)
from e2e.admin.harness.zulip_rig import ZulipIds

#: The break-glass key every fake participant gets (§1.7): the deployer's, the development
#: machine's.
BREAK_GLASS = "/etc/zab-admin/break-glass/deployer.pub"
REFSERVE_URL = "https://files.mathagents.org"
#: `zab-admin-e2e`'s `gifts_step` (#709): "Start here"'s first sentence, with characters outside
#: ASCII and a link, which A9 reads back from a fresh sandbox (`harness/start_here.py`) and A20
#: finds in its `!adopt-spare`'s `zulip_provision.py` step. `zab-admin-e2e2` has none: the
#: release's default.
GIFTS_STEP = (
    "Accept your gift plans: Claude Max from Anthropic's e-mail « Your invitation », and "
    "ChatGPT Pro through [the e2e form](https://example.org/zab-admin-e2e/gifts)."
)
#: `zab-admin-e2e`'s `mention_after_s` (#711), not the default 120, so that A6 finds the
#: workshop's value on its rollout's step, in its dry run and in each VM's config.toml, and A20
#: on its `!adopt-spare`'s two push_config.py steps. `zab-admin-e2e2` has none: 120.
MENTION_AFTER_S = 90
#: A11's console (no DNS record for a test console, Q4): an internal name to Caddy.
CONSOLE_URL = "https://admin-e2e.localhost"
GITHUB_ORG = "MathAgents"


def _q(value: object) -> str:
    """A TOML value: JSON's strings, integers and arrays are TOML's."""
    return json.dumps(value, ensure_ascii=False)


#: A9's plan TTL (`ending`): a teardown planned before a `!protect off` is approved after it.
ENDING_TTL_MINUTES = 15


def render(
    ids: ZulipIds,
    *,
    region: str,
    ami: str,
    groups: dict[str, str],
    ttl_minutes: int = 2,
    destructive_approvals: int = 1,
    e2e_organizers: tuple[int, ...] = (),
) -> str:
    organizers = {E2E.name: list(e2e_organizers), E2E2.name: [ids.tester2]}
    lines = [
        "# The admin e2e test server's admin.toml (docs/ADMIN.md §7; issue #356): generated by",
        "# tests/e2e/admin/run.py. Never commit it.",
        'provider = "aws"',
        f"admins = {_q([ids.tester])}",
        f"deployers = {_q([ids.tester])}",
        f"destructive_approvals = {destructive_approvals}",
        f"plan_ttl_minutes = {ttl_minutes}",
        'release = "rc"',
        f"console_url = {_q(CONSOLE_URL)}",
        "",
        "[global]",
        f"scope = {_q(SCOPE[1])}",
        f"regions = {_q([region])}",
        f"instance_types = {_q([PARTICIPANT_TYPE])}",
        f"tags = {_q(['='.join(TEST_ROLE)])}",
        'zuliprc = "/etc/zab-admin/secrets/global.zuliprc"',
        f"user_id = {ids.bots[GLOBAL_BOT][0]}",
        f"channels = {_q([ids.channels[ADMINS_CHANNEL]])}",
    ]
    for ws in (E2E, E2E2):
        lines += ["", *_workshop(ws, ids, organizers[ws.name], region, ami, groups[ws.name])]
    return "\n".join(lines) + "\n"


def ending(ids: ZulipIds, *, region: str, ami: str, groups: dict[str, str]) -> str:
    """A9's admin.toml (module doc): the rig's, with two approvers for the destructive verbs,
    `zab-tester2` a second organizer of `zab-admin-e2e`, and a 15-minute plan TTL."""
    return render(ids, region=region, ami=ami, groups=groups, ttl_minutes=ENDING_TTL_MINUTES,
                  destructive_approvals=2, e2e_organizers=(ids.tester2,))  # fmt: skip


def _workshop(
    ws: Workshop, ids: ZulipIds, organizers: list[int], region: str, ami: str, group: str
) -> list[str]:
    home = f"/var/lib/zab-admin/ws/{ws.name}"
    uid, email = ids.bots[ws.bot]
    return [
        "[[workshop]]",
        f"name = {_q(ws.name)}",
        f"github_org = {_q(GITHUB_ORG)}",
        f"refserve_url = {_q(REFSERVE_URL)}",
        f'roster = "{home}/roster.csv"',
        f'out_dir = "{home}/out"',
        f"organizers = {_q(organizers)}",
        *([f"mention_after_s = {MENTION_AFTER_S}"] if ws is E2E else []),
        f"alerts_channel = {ids.channels[ws.alerts]}",
        *([f"channel = {ids.channels[ws.participants]}"] if ws.participants else []),
        *([f"gifts_step = {_q(GIFTS_STEP)}"] if ws is E2E else []),
        "[workshop.bot]",
        f'zuliprc = "/etc/zab-admin/secrets/bots/{ws.name}.zuliprc"',
        f"user_id = {uid}",
        f"email = {_q(email)}",
        f"channels = {_q([ids.channels[ws.channel]])}",
        "[workshop.aws]",
        f"region = {_q(region)}",
        f"ami = {_q(ami)}",
        f"security_group = {_q(group)}",
        f"instance_types = {_q([PARTICIPANT_TYPE])}",
        f"key_name = {_q(ws.key_name)}",
        f"admin_keys = {_q([BREAK_GLASS])}",
    ]


def allowed_signers(signing_pub: str) -> str:
    """The release signers (§1.6): the rig's test-only key, for git's `git` namespace."""
    return f'zab-admin-e2e@example.org namespaces="git" {signing_pub.strip()}\n'
